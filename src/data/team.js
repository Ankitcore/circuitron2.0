/**
 * Safely retrieve custom members from browser localStorage
 */
export function getCustomMembers() {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(CUSTOM_MEMBERS_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch (err) {
    console.error("Failed to parse custom members from localStorage:", err);
    return [];
  }
}

/**
 * Save custom members array to localStorage and notify all listeners
 */
export function saveCustomMembers(members) {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(CUSTOM_MEMBERS_KEY, JSON.stringify(members));
    window.dispatchEvent(new CustomEvent("tx2_members_updated", { detail: members }));
  } catch (err) {
    console.error("Failed to save custom members to localStorage:", err);
  }
}

/**
 * Asynchronously sync custom member to the central cloud registry (/api/members)
 */
export async function syncMemberToCloud(member) {
  if (!member || typeof window === "undefined") return;
  try {
    await fetch("/api/members", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ member }),
      keepalive: true,
    });
  } catch (err) {
    console.warn("Cloud sync error for member:", err);
  }
}

/**
 * Asynchronously sync all custom members to the central cloud registry (/api/members)
 */
export async function syncAllMembersToCloud() {
  if (typeof window === "undefined") return;
  try {
    const custom = getCustomMembers();
    if (custom.length === 0) return;
    await fetch("/api/members", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ members: custom }),
      keepalive: true,
    });
  } catch (err) {
    console.warn("Cloud sync error for all members:", err);
  }
}

/**
 * Fetch and merge custom members from central cloud registry
 */
export async function fetchMembersFromCloud() {
  if (typeof window === "undefined") return [];
  try {
    const res = await fetch("/api/members");
    if (!res.ok) return [];
    const json = await res.json();
    if (json.success && Array.isArray(json.members) && json.members.length > 0) {
      const local = getCustomMembers();
      const localMap = new Map(local.map((m) => [m.id?.toUpperCase(), m]));
      let added = false;
      json.members.forEach((m) => {
        if (m && m.id && !localMap.has(m.id.toUpperCase())) {
          localMap.set(m.id.toUpperCase(), m);
          added = true;
        }
      });
      if (added) {
        const merged = Array.from(localMap.values());
        saveCustomMembers(merged);
        return merged;
      }
    }
  } catch (err) {
    console.warn("Fetch cloud members error:", err);
  }
  return getCustomMembers();
}

/**
 * Normalize tier string to standard key ('executive' | 'core' | 'participant' | 'volunteer' | 'faculty')
 * Safely checks both tier string and optional ID prefix (e.g. TX2-FC-)
 */
export function normalizeTierKey(tierInput = "", id = "") {
  const idStr = String(id || "").trim().toUpperCase();
  if (idStr.startsWith("TX2-FC") || idStr.includes("-FC-")) return "faculty";
  if (idStr.startsWith("TX2-EX") || idStr.includes("-EX-")) return "executive";
  if (idStr.startsWith("TX2-CT") || idStr.includes("-CT-")) return "core";
  if (idStr.startsWith("TX2-PT") || idStr.includes("-PT-")) return "participant";
  if (idStr.startsWith("TX2-VL") || idStr.includes("-VL-")) return "volunteer";

  const t = String(tierInput || "").trim().toLowerCase();
  if (t.includes("exec")) return "executive";
  if (t.includes("core")) return "core";
  if (t.includes("part")) return "participant";
  if (t.includes("vol")) return "volunteer";
  if (
    t.includes("fac") ||
    t.includes("acad") ||
    t.includes("advis") ||
    t.includes("mentor") ||
    t.includes("coord")
  ) {
    return "faculty";
  }
  return "participant";
}

/**
 * Generate a collision-free unique Member ID (e.g., TX2-PT-8294)
 */
export function generateUniqueMemberId(tierInput = "participant") {
  const tierKey = normalizeTierKey(tierInput);
  const cfg = TIER_CONFIG[tierKey] || TIER_CONFIG.participant;
  const existing = getAllMembers();
  const existingIds = new Set(existing.map((m) => m.id?.toUpperCase()));

  for (let attempt = 0; attempt < 500; attempt++) {
    const randomSuffix = Math.floor(1000 + Math.random() * 9000);
    const candidate = `${cfg.prefix}${randomSuffix}`;
    if (!existingIds.has(candidate)) {
      return candidate;
    }
  }
  // Fallback timestamp-based code
  return `${cfg.prefix}${Date.now().toString().slice(-4)}`;
}

